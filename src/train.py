def make_checkpoint(model, epoch, best_metric, dataset, args):
    return {
        "model_state_dict": model.state_dict(),
        "epoch": epoch,
        "best_metric": best_metric,

        "model_type": "JointUWProbabilisticMLP",
        "y_dim": dataset.y_dim,
        "U_dim": dataset.U_dim,
        "K_obs": dataset.K,
        "N_vertices": dataset.N,
        "z_dim": args.z_dim,
        "hidden_dim": args.hidden_dim,
        "logvar_min": args.logvar_min,
        "logvar_max": args.logvar_max,

        "lambda_obs": args.lambda_obs,
        "lambda_U": args.lambda_U,
        "lambda_W": args.lambda_W,
        "beta_kl": args.beta_kl,
        "normalize_y_for_projection": bool(not args.no_normalize_y_for_projection),
    }


def train(args):
    set_seed(args.seed)

    os.makedirs(args.weight_dir, exist_ok=True)
    os.makedirs(args.log_dir, exist_ok=True)

    device = torch.device("cuda" if torch.cuda.is_available() and not args.cpu else "cpu")

    print("Using device:", device)
    print("data_dir:", os.path.abspath(args.data_dir))
    print("lambda_obs:", args.lambda_obs)
    print("lambda_U:", args.lambda_U)
    print("lambda_W:", args.lambda_W)
    print("beta_kl:", args.beta_kl)
    print("sample_z:", not args.no_sample_z)
    print("logvar range:", args.logvar_min, args.logvar_max)

    dataset = SurfaceFrameDataset(args.data_dir)

    # Save normalization.
    norm_path = os.path.join(args.weight_dir, "normalization.npz")
    np.savez(
        norm_path,
        y_mean=dataset.y_mean,
        y_std=dataset.y_std,
        U_mean=dataset.U_mean,
        U_std=dataset.U_std,
    )
    print("Saved normalization to:", norm_path)

    # Torch constants for denormalization.
    U_mean_t = torch.from_numpy(dataset.U_mean.astype(np.float32)).to(device)  # [1,U_dim]
    U_std_t = torch.from_numpy(dataset.U_std.astype(np.float32)).to(device)    # [1,U_dim]

    loader = DataLoader(
        dataset,
        batch_size=args.batch_size,
        shuffle=True,
        num_workers=args.num_workers,
        drop_last=False,
        pin_memory=torch.cuda.is_available() and not args.cpu,
    )

    model = JointUWProbabilisticMLP(
        y_dim=dataset.y_dim,
        U_dim=dataset.U_dim,
        K_obs=dataset.K,
        N_vertices=dataset.N,
        z_dim=args.z_dim,
        hidden_dim=args.hidden_dim,
        logvar_min=args.logvar_min,
        logvar_max=args.logvar_max,
        dropout=args.dropout,
    ).to(device)

    optimizer = torch.optim.AdamW(
        model.parameters(),
        lr=args.lr,
        weight_decay=args.weight_decay,
    )

    best_metric = float("inf")
    best_path = os.path.join(args.weight_dir, args.save_name)
    last_path = os.path.join(args.weight_dir, "last_" + args.save_name)
    log_path = os.path.join(args.log_dir, "train_log_joint_UW.csv")

    with open(log_path, "w", newline="") as f:
        writer = csv.writer(f)
        writer.writerow([
            "epoch",
            "loss",
            "obs_loss_predW",
            "obs_loss_gtW",
            "U_nll",
            "U_mse_norm",
            "U_rmse_norm",
            "W_ce",
            "W_top1_acc",
            "kl",
            "mean_U_std_norm",
            "best_metric",
        ])

    sample_z = not args.no_sample_z
    normalize_y_for_projection = not args.no_normalize_y_for_projection

    for epoch in range(args.epochs):
        model.train()

        total_loss = 0.0
        total_obs = 0.0
        total_obs_gtW = 0.0
        total_U_nll = 0.0
        total_U_mse = 0.0
        total_W_ce = 0.0
        total_W_acc = 0.0
        total_kl = 0.0
        total_std = 0.0

        for batch in loader:
            y_norm = batch["y_norm"].to(device, non_blocking=True)       # [B,2K]
            y_phys = batch["y_phys"].to(device, non_blocking=True)       # [B,K,2]
            U_norm = batch["U_norm"].to(device, non_blocking=True)       # [B,3N]
            U_phys_gt = batch["U_phys"].to(device, non_blocking=True)    # [B,N,3]

            X0 = batch["X0"].to(device, non_blocking=True)               # [B,N,3]
            W_idx = batch["W_idx"].to(device, non_blocking=True)         # [B,K,3]
            W_val = batch["W_val"].to(device, non_blocking=True)         # [B,K,3]

            camera_K = batch["camera_K"].to(device, non_blocking=True)
            camera_R = batch["camera_R"].to(device, non_blocking=True)
            camera_t = batch["camera_t"].to(device, non_blocking=True)

            U_mu_norm, U_logvar_norm, W_logits, z_mu, z_logvar = model(
                y_norm,
                sample_z=sample_z,
            )

            B = y_norm.shape[0]

            # Denormalize U for observation operator.
            U_mu_phys_flat = U_mu_norm * U_std_t + U_mean_t
            U_mu_phys = U_mu_phys_flat.view(B, dataset.N, 3)

            # Observation loss using predicted W.
            y_hat_predW, W_soft = observation_operator_softW(
                U_phys=U_mu_phys,
                W_logits=W_logits,
                X0=X0,
                Kmat=camera_K,
                R=camera_R,
                t=camera_t,
                normalize_y=normalize_y_for_projection,
            )
            obs_loss_predW = torch.mean((y_hat_predW - y_phys) ** 2)

            # Oracle observation loss using GT W. This is logged and can optionally be used.
            y_hat_gtW = observation_operator_gtW(
                U_phys=U_mu_phys,
                X0=X0,
                sparse_idx=W_idx,
                sparse_val=W_val,
                Kmat=camera_K,
                R=camera_R,
                t=camera_t,
                normalize_y=normalize_y_for_projection,
            )
            obs_loss_gtW = torch.mean((y_hat_gtW - y_phys) ** 2)

            if args.use_gtW_obs_loss:
                obs_loss = obs_loss_gtW
            else:
                obs_loss = obs_loss_predW

            # U auxiliary probabilistic reconstruction in normalized U-space.
            U_nll = gaussian_nll_loss(U_norm, U_mu_norm, U_logvar_norm)
            U_mse_norm = mse_loss(U_norm, U_mu_norm)

            # W supervision from sparse barycentric GT.
            W_ce = soft_ce_loss_from_sparse(W_logits, W_idx, W_val)

            # KL regularization.
            kl = kl_loss(z_mu, z_logvar)

            loss = (
                args.lambda_obs * obs_loss
                + args.lambda_U * U_nll
                + args.lambda_W * W_ce
                + args.beta_kl * kl
            )

            optimizer.zero_grad(set_to_none=True)
            loss.backward()

            if args.grad_clip > 0:
                torch.nn.utils.clip_grad_norm_(model.parameters(), args.grad_clip)

            optimizer.step()

            with torch.no_grad():
                U_std_norm = torch.exp(0.5 * U_logvar_norm)

                # W top-1 accuracy: predicted dominant vertex vs GT dominant bary vertex.
                pred_top = torch.argmax(W_logits, dim=-1)          # [B,K]
                gt_top_local = torch.argmax(W_val, dim=-1)         # [B,K]
                gt_top = torch.gather(W_idx, dim=-1, index=gt_top_local.unsqueeze(-1)).squeeze(-1)
                W_top1_acc = (pred_top == gt_top).float().mean()

            total_loss += float(loss.item())
            total_obs += float(obs_loss_predW.item())
            total_obs_gtW += float(obs_loss_gtW.item())
            total_U_nll += float(U_nll.item())
            total_U_mse += float(U_mse_norm.item())
            total_W_ce += float(W_ce.item())
            total_W_acc += float(W_top1_acc.item())
            total_kl += float(kl.item())
            total_std += float(U_std_norm.mean().item())

        nb = len(loader)
        avg_loss = total_loss / nb
        avg_obs = total_obs / nb
        avg_obs_gtW = total_obs_gtW / nb
        avg_U_nll = total_U_nll / nb
        avg_U_mse = total_U_mse / nb
        avg_U_rmse = float(np.sqrt(avg_U_mse))
        avg_W_ce = total_W_ce / nb
        avg_W_acc = total_W_acc / nb
        avg_kl = total_kl / nb
        avg_std = total_std / nb

        # Best model selection.
        # Use total loss by default because this is joint training.
        if args.select_best_by == "loss":
            current_metric = avg_loss
        elif args.select_best_by == "obs":
            current_metric = avg_obs
        elif args.select_best_by == "U_mse":
            current_metric = avg_U_mse
        elif args.select_best_by == "W_ce":
            current_metric = avg_W_ce
        else:
            raise ValueError(f"Unknown select_best_by: {args.select_best_by}")

        if current_metric < best_metric:
            best_metric = current_metric
            ckpt = make_checkpoint(model, epoch, best_metric, dataset, args)
            if args.safe_save:
                safe_torch_save(ckpt, best_path)
            else:
                torch.save(ckpt, best_path)

        if args.save_last and ((epoch % args.save_last_every == 0) or (epoch == args.epochs - 1)):
            ckpt = make_checkpoint(model, epoch, best_metric, dataset, args)
            if args.safe_save:
                safe_torch_save(ckpt, last_path)
            else:
                torch.save(ckpt, last_path)

        with open(log_path, "a", newline="") as f:
            writer = csv.writer(f)
            writer.writerow([
                epoch,
                avg_loss,
                avg_obs,
                avg_obs_gtW,
                avg_U_nll,
                avg_U_mse,
                avg_U_rmse,
                avg_W_ce,
                avg_W_acc,
                avg_kl,
                avg_std,
                best_metric,
            ])

        if epoch % args.print_every == 0:
            print(
                f"Epoch {epoch:04d} | "
                f"loss={avg_loss:.6e} | "
                f"obs_predW={avg_obs:.6e} | "
                f"obs_gtW={avg_obs_gtW:.6e} | "
                f"U_nll={avg_U_nll:.6e} | "
                f"U_rmse_norm={avg_U_rmse:.6e} | "
                f"W_ce={avg_W_ce:.6e} | "
                f"W_acc={avg_W_acc:.4f} | "
                f"kl={avg_kl:.6e} | "
                f"mean_U_std_norm={avg_std:.6e} | "
                f"best={best_metric:.6e}"
            )

    print("\nTraining finished.")
    print("Best model saved to:", best_path)
    if args.save_last:
        print("Last model saved to:", last_path)
    print("Normalization saved to:", norm_path)
    print("Log saved to:", log_path)
    print("Best metric:", best_metric)


