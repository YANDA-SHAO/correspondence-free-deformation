def set_seed(seed: int):
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    torch.cuda.manual_seed_all(seed)


def safe_torch_save(obj, path):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp_path = path + ".tmp"
    torch.save(obj, tmp_path)
    os.replace(tmp_path, path)


class SurfaceFrameDataset(Dataset):
    """
    Frame-level dataset for surface-correspondence training.

    Each item returns:
        y_norm_flat:      [2K]
        y_phys:           [K,2]
        U_norm_flat:      [3N]
        U_phys:           [N,3]
        X0:               [N,3]
        W_sparse_idx:     [K,3]
        W_sparse_val:     [K,3]
        camera_K:         [3,3]
        camera_R:         [3,3]
        camera_t:         [3]
        sample_id:        int
        frame_id:         int

    Normalization:
        y_mean/y_std and U_mean/U_std are computed from training split only.
    """

    def __init__(self, root: str):
        self.root = root
        self.sample_dirs = sorted(glob.glob(os.path.join(root, "sample_*")))

        if len(self.sample_dirs) == 0:
            raise ValueError(
                f"No sample_* folders found in {root}. "
                f"Expected data/dataset_v2_surface/train/sample_XXXX."
            )

        # Per-sample storage.
        self.samples: List[Dict] = []
        y_all = []
        U_all = []

        for sid, d in enumerate(self.sample_dirs):
            required = [
                "X0.npy",
                "U_seq.npy",
                "y.npy",
                "W_gt_sparse_indices.npy",
                "W_gt_sparse_values.npy",
                "camera_K.npy",
                "camera_R.npy",
                "camera_t.npy",
            ]
            for f in required:
                p = os.path.join(d, f)
                if not os.path.exists(p):
                    raise FileNotFoundError(f"Missing required file: {p}")

            X0 = np.load(os.path.join(d, "X0.npy")).astype(np.float32)                 # [N,3]
            U_seq = np.load(os.path.join(d, "U_seq.npy")).astype(np.float32)           # [T,N,3]
            y = np.load(os.path.join(d, "y.npy")).astype(np.float32)                   # [T,K,2]
            W_idx = np.load(os.path.join(d, "W_gt_sparse_indices.npy")).astype(np.int64)  # [K,3]
            W_val = np.load(os.path.join(d, "W_gt_sparse_values.npy")).astype(np.float32) # [K,3]
            camera_K = np.load(os.path.join(d, "camera_K.npy")).astype(np.float32)
            camera_R = np.load(os.path.join(d, "camera_R.npy")).astype(np.float32)
            camera_t = np.load(os.path.join(d, "camera_t.npy")).astype(np.float32)

            if y.ndim != 3 or y.shape[-1] != 2:
                raise ValueError(f"Expected y [T,K,2], got {y.shape} in {d}")
            if U_seq.ndim != 3 or U_seq.shape[-1] != 3:
                raise ValueError(f"Expected U_seq [T,N,3], got {U_seq.shape} in {d}")
            if W_idx.shape != W_val.shape or W_idx.ndim != 2 or W_idx.shape[1] != 3:
                raise ValueError(f"Expected W sparse [K,3], got {W_idx.shape}, {W_val.shape} in {d}")

            T = min(y.shape[0], U_seq.shape[0])
            y = y[:T]
            U_seq = U_seq[:T]

            y_flat = y.reshape(T, -1)
            U_flat = U_seq.reshape(T, -1)

            y_all.append(y_flat)
            U_all.append(U_flat)

            self.samples.append({
                "dir": d,
                "X0": X0,
                "U_seq": U_seq,
                "y": y,
                "W_idx": W_idx,
                "W_val": W_val,
                "camera_K": camera_K,
                "camera_R": camera_R,
                "camera_t": camera_t,
                "T": T,
                "N": X0.shape[0],
                "K": y.shape[1],
            })

        y_all_np = np.concatenate(y_all, axis=0).astype(np.float32)
        U_all_np = np.concatenate(U_all, axis=0).astype(np.float32)

        self.y_mean = y_all_np.mean(axis=0, keepdims=True).astype(np.float32)
        self.y_std = (y_all_np.std(axis=0, keepdims=True) + 1e-8).astype(np.float32)

        self.U_mean = U_all_np.mean(axis=0, keepdims=True).astype(np.float32)
        self.U_std = (U_all_np.std(axis=0, keepdims=True) + 1e-8).astype(np.float32)

        # Flatten frame index.
        self.frame_index = []
        for sid, s in enumerate(self.samples):
            for t in range(s["T"]):
                self.frame_index.append((sid, t))

        # Dimensional consistency.
        Ns = sorted(set(s["N"] for s in self.samples))
        Ks = sorted(set(s["K"] for s in self.samples))
        if len(Ns) != 1:
            raise ValueError(f"All samples must have same N for current MLP model. Got {Ns}")
        if len(Ks) != 1:
            raise ValueError(f"All samples must have same K. Got {Ks}")

        self.N = Ns[0]
        self.K = Ks[0]
        self.y_dim = 2 * self.K
        self.U_dim = 3 * self.N

        print("Loaded surface dataset")
        print("  root:", os.path.abspath(root))
        print("  num samples:", len(self.samples))
        print("  num frames:", len(self.frame_index))
        print("  N vertices:", self.N)
        print("  K tracks:", self.K)
        print("  y_dim:", self.y_dim)
        print("  U_dim:", self.U_dim)
        print("  y mean/std:", float(self.y_mean.mean()), float(self.y_std.mean()))
        print("  U mean/std:", float(self.U_mean.mean()), float(self.U_std.mean()))

    def __len__(self):
        return len(self.frame_index)

    def __getitem__(self, idx):
        sid, tid = self.frame_index[idx]
        s = self.samples[sid]

        y_phys = s["y"][tid]          # [K,2]
        U_phys = s["U_seq"][tid]      # [N,3]

        y_flat = y_phys.reshape(1, -1)
        U_flat = U_phys.reshape(1, -1)

        y_norm_flat = ((y_flat - self.y_mean) / self.y_std).reshape(-1).astype(np.float32)
        U_norm_flat = ((U_flat - self.U_mean) / self.U_std).reshape(-1).astype(np.float32)

        return {
            "y_norm": torch.from_numpy(y_norm_flat),
            "y_phys": torch.from_numpy(y_phys.astype(np.float32)),
            "U_norm": torch.from_numpy(U_norm_flat),
            "U_phys": torch.from_numpy(U_phys.astype(np.float32)),
            "X0": torch.from_numpy(s["X0"].astype(np.float32)),
            "W_idx": torch.from_numpy(s["W_idx"].astype(np.int64)),
            "W_val": torch.from_numpy(s["W_val"].astype(np.float32)),
            "camera_K": torch.from_numpy(s["camera_K"].astype(np.float32)),
            "camera_R": torch.from_numpy(s["camera_R"].astype(np.float32)),
            "camera_t": torch.from_numpy(s["camera_t"].astype(np.float32)),
            "sample_id": torch.tensor(sid, dtype=torch.long),
            "frame_id": torch.tensor(tid, dtype=torch.long),
        }


