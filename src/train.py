def parse_args():
    parser = argparse.ArgumentParser()

    parser.add_argument("--data_dir", type=str, default=DEFAULT_DATA_DIR)
    parser.add_argument("--weight_dir", type=str, default=DEFAULT_WEIGHT_DIR)
    parser.add_argument("--log_dir", type=str, default=DEFAULT_LOG_DIR)
    parser.add_argument("--save_name", type=str, default="joint_UW_surface_best.pth")

    parser.add_argument("--epochs", type=int, default=2000)
    parser.add_argument("--batch_size", type=int, default=64)
    parser.add_argument("--lr", type=float, default=1e-3)
    parser.add_argument("--weight_decay", type=float, default=1e-6)
    parser.add_argument("--num_workers", type=int, default=0)
    parser.add_argument("--seed", type=int, default=42)

    parser.add_argument("--z_dim", type=int, default=32)
    parser.add_argument("--hidden_dim", type=int, default=256)
    parser.add_argument("--dropout", type=float, default=0.0)

    # Loss weights.
    # Suggested stable start:
    #   lambda_U keeps deformation physically meaningful.
    #   lambda_W teaches correspondence.
    #   lambda_obs closes the inverse loop through the camera.
    parser.add_argument("--lambda_obs", type=float, default=10.0)
    parser.add_argument("--lambda_U", type=float, default=1.0)
    parser.add_argument("--lambda_W", type=float, default=0.1)
    parser.add_argument("--beta_kl", type=float, default=1e-4)

    # U uncertainty in normalized U-space.
    parser.add_argument("--logvar_min", type=float, default=-8.0)
    parser.add_argument("--logvar_max", type=float, default=2.0)

    parser.add_argument("--grad_clip", type=float, default=1.0)
    parser.add_argument("--print_every", type=int, default=50)

    parser.add_argument(
        "--select_best_by",
        type=str,
        default="loss",
        choices=["loss", "obs", "U_mse", "W_ce"],
    )

    # Debug / ablation flags.
    parser.add_argument(
        "--use_gtW_obs_loss",
        action="store_true",
        help="Use GT W for observation loss. Useful as oracle/debug. Default uses predicted W.",
    )
    parser.add_argument(
        "--no_normalize_y_for_projection",
        action="store_true",
        help="If set, observation projection loss is computed in pixel units. Default uses y_pixel/fx units.",
    )
    parser.add_argument("--no_sample_z", action="store_true")
    parser.add_argument("--cpu", action="store_true")

    parser.add_argument("--safe_save", action="store_true", default=True)
    parser.add_argument("--save_last", action="store_true")
    parser.add_argument("--save_last_every", type=int, default=100)

    return parser.parse_args()

if __name__ == "__main__":
    train(parse_args())
