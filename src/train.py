# src/train.py
"""
Final training script for surface-correspondence Bayesian inversion.

This version is designed for dataset_v2_surface generated by the new generate_data.py.

Core idea:
    Input:
        y_t: sparse 2D tracking displacement, [K,2]

    Model predicts:
        U_mu_norm:     dense displacement mean in normalized U-space, [N,3]
        U_logvar_norm: dense displacement log-variance in normalized U-space, [N,3]
        W_logits:      soft correspondence logits, [K,N]
        z_mu, z_logvar

    Differentiable observation operator:
        W = softmax(W_logits, dim=-1)
        X_k = sum_i W[k,i] X0_i
        U_k = sum_i W[k,i] U_i
        y_hat_k = project(X_k + U_k) - project(X_k)

    Training loss:
        L = lambda_obs * L_obs(y, y_hat)
          + lambda_U   * L_U(U_gt, U_mu, U_logvar)
          + lambda_W   * L_W(W_gt, W_logits)
          + beta_kl    * KL(q(z|y)||N(0,I))

Important:
    - observed_idx is NOT used as model input.
    - W_gt comes from surface barycentric correspondence:
        W_gt_sparse_indices.npy [K,3]
        W_gt_sparse_values.npy  [K,3]
    - Observation loss is computed in physical normalized-pixel y-space.
    - U auxiliary loss is computed in normalized U-space.
"""

