# src/generate_data.py
"""
Dataset-level generator for sparse 2D tracking trajectories -> dense 3D beam displacement.

Final-testing version:
1. Observations are sampled on the continuous mesh surface, not only at vertices.
2. Each observed 2D track has mesh-surface correspondence:
      obs_face_id[k]
      obs_face_vertices[k] = [i1, i2, i3]
      obs_barycentric[k] = [w1, w2, w3]
3. Sparse soft correspondence ground truth is saved:
      W_gt_sparse_indices[k] = [i1, i2, i3]
      W_gt_sparse_values[k]  = [w1, w2, w3]
4. Optional dense W_gt can be saved with --save_dense_W.
5. y is generated by barycentric interpolation followed by pinhole projection:
      X_k = sum_j w_j X0[i_j]
      U_k(t) = sum_j w_j U_seq[t, i_j]
      y(t,k) = project(X_k + U_k(t)) - project(X_k)

Output:
    data/dataset_v2_surface/{train,val,test}/sample_XXXX/
"""

import os
import json
import argparse
from pathlib import Path

import numpy as np
import trimesh


# ============================================================
# Physics: Euler-Bernoulli cantilever first mode
# ============================================================

def cantilever_first_mode_shape(x, L):
    betaL = 1.875104068711961
    beta = betaL / L

    sigma = (
        (np.cosh(betaL) + np.cos(betaL)) /
        (np.sinh(betaL) + np.sin(betaL))
    )

    phi = (
        np.cosh(beta * x)
        - np.cos(beta * x)
        - sigma * (np.sinh(beta * x) - np.sin(beta * x))
    )

    phi = phi / (np.max(np.abs(phi)) + 1e-12)
    return phi.astype(np.float32)


def cantilever_first_natural_frequency(E, I, rho, A, L):
    betaL = 1.875104068711961
    omega1 = betaL ** 2 * np.sqrt(E * I / (rho * A * L ** 4))
    return float(omega1)


def generate_free_vibration(
    X0,
    youngs_modulus,
    density,
    width,
    height,
    length,
    amplitude,
    T,
    duration,
    length_axis=0,
    displacement_axis=1,
    phase=0.0,
    frequency_scale=1.0,
):
    """
    First-mode free vibration:
        U(x,t) = amplitude * phi_1(x) * cos(frequency_scale * omega_1 * t + phase)
    """
    area = width * height

    # Keep previous convention to avoid changing existing behaviour.
    inertia = height * (width ** 3) / 12.0

    omega1_base = cantilever_first_natural_frequency(
        youngs_modulus, inertia, density, area, length
    )
    omega1 = float(frequency_scale * omega1_base)

    x_raw = X0[:, length_axis]
    x = x_raw - x_raw.min()
    x = x / (x.max() + 1e-12) * length

    phi = cantilever_first_mode_shape(x, length)

    U = np.zeros_like(X0, dtype=np.float32)
    U[:, displacement_axis] = amplitude * phi

    t = np.linspace(0.0, duration, T, dtype=np.float32)
    amp_t = np.cos(omega1 * t + phase).astype(np.float32)

    U_seq = amp_t[:, None, None] * U[None, :, :]

    return {
        "U": U.astype(np.float32),
        "U_seq": U_seq.astype(np.float32),
        "amp_t": amp_t.astype(np.float32),
        "phi_1": phi.astype(np.float32),
        "omega1_base": omega1_base,
        "omega1": omega1,
        "area": area,
        "inertia": inertia,
    }


