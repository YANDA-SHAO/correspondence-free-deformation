def generate_sample(
    mesh,
    mesh_path,
    output_dir,
    seed=0,
    split="train",
    sample_id=0,
    youngs_modulus=69e9,
    density=2700.0,
    width=0.05,
    height=0.10,
    length=1.0,
    amplitude=0.03,
    T=200,
    duration=1.0,
    K_obs=20,
    noise_std=1e-5,
    length_axis=0,
    displacement_axis=1,
    fx=800.0,
    fy=800.0,
    cx=320.0,
    cy=240.0,
    camera_eye=None,
    camera_target=None,
    normalize_y=True,
    free_end_ratio=0.10,
    phase=0.0,
    frequency_scale=1.0,
    observation_mode="surface",
    area_weighted_surface=True,
    save_dense_W=False,
):
    os.makedirs(output_dir, exist_ok=True)
    rng = np.random.default_rng(seed)

    X0 = np.asarray(mesh.vertices, dtype=np.float32)
    faces = np.asarray(mesh.faces, dtype=np.int64)
    if faces is None or len(faces) == 0:
        raise ValueError("Mesh has no triangular faces. Surface observation requires mesh.faces.")
    N = X0.shape[0]

    vib = generate_free_vibration(
        X0=X0,
        youngs_modulus=youngs_modulus,
        density=density,
        width=width,
        height=height,
        length=length,
        amplitude=amplitude,
        T=T,
        duration=duration,
        length_axis=length_axis,
        displacement_axis=displacement_axis,
        phase=phase,
        frequency_scale=frequency_scale,
    )

    U = vib["U"]
    U_seq = vib["U_seq"]
    amp_t = vib["amp_t"]
    phi_1 = vib["phi_1"]

    if observation_mode == "surface":
        obs_face_id, obs_face_vertices, obs_barycentric, X_obs0, observed_idx, candidate_face_id = sample_observed_surface_points(
            X0=X0,
            faces=faces,
            rng=rng,
            K_obs=K_obs,
            length_axis=length_axis,
            free_end_ratio=free_end_ratio,
            area_weighted=area_weighted_surface,
        )
        U_obs_seq = interpolate_surface_displacement(U_seq, obs_face_vertices, obs_barycentric)
        W_sparse_indices, W_sparse_values = make_sparse_W_gt(obs_face_vertices, obs_barycentric)
        W_gt_dense = make_dense_W_gt(N, obs_face_vertices, obs_barycentric) if save_dense_W else None

    elif observation_mode == "vertex":
        x_coord = X0[:, length_axis]
        x_max = x_coord.max()
        x_min = x_coord.min()
        threshold = x_max - free_end_ratio * (x_max - x_min)
        candidate_idx = np.where(x_coord >= threshold)[0]
        if len(candidate_idx) < K_obs:
            raise ValueError(f"Not enough free-end vertices for K_obs={K_obs}.")

        observed_idx = np.sort(rng.choice(candidate_idx, size=K_obs, replace=False)).astype(np.int64)
        X_obs0 = X0[observed_idx]
        U_obs_seq = U_seq[:, observed_idx, :]

        vertex_to_face = {}
        for f_id, tri in enumerate(faces):
            for local_j, vid in enumerate(tri):
                if int(vid) not in vertex_to_face:
                    vertex_to_face[int(vid)] = (f_id, local_j)

        obs_face_id = []
        obs_face_vertices = []
        obs_barycentric = []
        for vid in observed_idx:
            if int(vid) in vertex_to_face:
                f_id, local_j = vertex_to_face[int(vid)]
                tri = faces[f_id]
                bary = np.zeros(3, dtype=np.float32)
                bary[local_j] = 1.0
            else:
                f_id = 0
                tri = faces[0]
                bary = np.array([1.0, 0.0, 0.0], dtype=np.float32)
            obs_face_id.append(f_id)
            obs_face_vertices.append(tri)
            obs_barycentric.append(bary)

        obs_face_id = np.asarray(obs_face_id, dtype=np.int64)
        obs_face_vertices = np.asarray(obs_face_vertices, dtype=np.int64)
        obs_barycentric = np.asarray(obs_barycentric, dtype=np.float32)
        candidate_face_id = np.unique(obs_face_id).astype(np.int64)
        W_sparse_indices, W_sparse_values = make_sparse_W_gt(obs_face_vertices, obs_barycentric)
        W_gt_dense = make_dense_W_gt(N, obs_face_vertices, obs_barycentric) if save_dense_W else None

    else:
        raise ValueError(f"Unknown observation_mode: {observation_mode}")

    K = make_camera_intrinsics(fx, fy, cx, cy)

    if camera_eye is None or camera_target is None:
        camera_eye, camera_target = sample_camera_eye(rng=rng, X0=X0, length_axis=length_axis)
    else:
        camera_eye = np.asarray(camera_eye, dtype=np.float32)
        camera_target = np.asarray(camera_target, dtype=np.float32)

    R, t = look_at_camera(camera_eye, camera_target)

    uv0, Xcam0 = perspective_project(X_obs0, K, R, t)
    uvt, Xcamt = perspective_project(X_obs0[None, :, :] + U_obs_seq, K, R, t)

    if np.any(Xcam0[:, 2] <= 1e-6) or np.any(Xcamt[..., 2] <= 1e-6):
        raise RuntimeError(f"Invalid camera for sample {sample_id}: some points are behind the camera.")

    y_pixel_clean = uvt - uv0[None, :, :]

    if normalize_y:
        y_clean = y_pixel_clean / fx
        y_unit = f"normalized pixel displacement, divided by fx={fx}"
    else:
        y_clean = y_pixel_clean
        y_unit = "pixel displacement"

    if noise_std > 0:
        noise = rng.normal(scale=noise_std, size=y_clean.shape).astype(np.float32)
    else:
        noise = np.zeros_like(y_clean, dtype=np.float32)

    y = (y_clean + noise).astype(np.float32)

    deformed_mesh = mesh.copy()
    deformed_mesh.vertices = X0 + U

    # Core files
    np.save(os.path.join(output_dir, "X0.npy"), X0.astype(np.float32))
    np.save(os.path.join(output_dir, "faces.npy"), faces.astype(np.int64))
    np.save(os.path.join(output_dir, "U.npy"), U.astype(np.float32))
    np.save(os.path.join(output_dir, "U_seq.npy"), U_seq.astype(np.float32))

    # Observation files
    np.save(os.path.join(output_dir, "y.npy"), y.astype(np.float32))
    np.save(os.path.join(output_dir, "y_clean.npy"), y_clean.astype(np.float32))
    np.save(os.path.join(output_dir, "y_pixel.npy"), y_pixel_clean.astype(np.float32))
    np.save(os.path.join(output_dir, "track_uv0.npy"), uv0.astype(np.float32))
    np.save(os.path.join(output_dir, "track_uv_seq.npy"), uvt.astype(np.float32))

    # Surface correspondence files
    np.save(os.path.join(output_dir, "obs_face_id.npy"), obs_face_id.astype(np.int64))
    np.save(os.path.join(output_dir, "obs_face_vertices.npy"), obs_face_vertices.astype(np.int64))
    np.save(os.path.join(output_dir, "obs_barycentric.npy"), obs_barycentric.astype(np.float32))
    np.save(os.path.join(output_dir, "W_gt_sparse_indices.npy"), W_sparse_indices.astype(np.int64))
    np.save(os.path.join(output_dir, "W_gt_sparse_values.npy"), W_sparse_values.astype(np.float32))
    if W_gt_dense is not None:
        np.save(os.path.join(output_dir, "W_gt_dense.npy"), W_gt_dense.astype(np.float32))

    # Backward compatibility
    np.save(os.path.join(output_dir, "observed_idx.npy"), observed_idx.astype(np.int64))
    np.save(os.path.join(output_dir, "candidate_free_end_face_id.npy"), candidate_face_id.astype(np.int64))

    # Camera files
    np.save(os.path.join(output_dir, "camera_K.npy"), K.astype(np.float32))
    np.save(os.path.join(output_dir, "camera_R.npy"), R.astype(np.float32))
    np.save(os.path.join(output_dir, "camera_t.npy"), t.astype(np.float32))
    np.save(os.path.join(output_dir, "camera_eye.npy"), camera_eye.astype(np.float32))
    np.save(os.path.join(output_dir, "camera_target.npy"), camera_target.astype(np.float32))

    # Physics files
    np.save(os.path.join(output_dir, "amp_t.npy"), amp_t.astype(np.float32))
    np.save(os.path.join(output_dir, "phi_1.npy"), phi_1.astype(np.float32))

    deformed_mesh.export(os.path.join(output_dir, "deformed_mesh.obj"))

    meta = {
        "mesh_path": str(mesh_path),
        "output_dir": str(output_dir),
        "split": split,
        "sample_id": int(sample_id),
        "seed": int(seed),
        "model": "Euler-Bernoulli cantilever first-mode free vibration",
        "physical_equation": "u(x,t) = A * phi_1(x) * cos(omega_1 * t + phase)",
        "youngs_modulus": float(youngs_modulus),
        "density": float(density),
        "width": float(width),
        "height": float(height),
        "area": float(vib["area"]),
        "moment_inertia": float(vib["inertia"]),
        "length": float(length),
        "amplitude": float(amplitude),
        "phase": float(phase),
        "frequency_scale": float(frequency_scale),
        "T": int(T),
        "duration": float(duration),
        "K_obs": int(K_obs),
        "free_end_ratio": float(free_end_ratio),
        "noise_std": float(noise_std),
        "length_axis": int(length_axis),
        "displacement_axis": int(displacement_axis),
        "omega1_base_rad_per_s": float(vib["omega1_base"]),
        "omega1_rad_per_s": float(vib["omega1"]),
        "frequency_hz": float(vib["omega1"] / (2.0 * np.pi)),
        "X0_shape": list(X0.shape),
        "faces_shape": list(faces.shape),
        "U_shape": list(U.shape),
        "U_seq_shape": list(U_seq.shape),
        "y_shape": list(y.shape),
        "projection": "pinhole perspective camera",
        "camera_intrinsics": {"fx": float(fx), "fy": float(fy), "cx": float(cx), "cy": float(cy)},
        "camera_eye": camera_eye.tolist(),
        "camera_target": camera_target.tolist(),
        "observation_mode": observation_mode,
        "correspondence_type": "surface barycentric soft correspondence" if observation_mode == "surface" else "vertex one-hot correspondence",
        "surface_files": {
            "obs_face_id": "obs_face_id.npy",
            "obs_face_vertices": "obs_face_vertices.npy",
            "obs_barycentric": "obs_barycentric.npy",
            "W_gt_sparse_indices": "W_gt_sparse_indices.npy",
            "W_gt_sparse_values": "W_gt_sparse_values.npy",
            "W_gt_dense": "W_gt_dense.npy" if save_dense_W else None,
        },
        "y_unit": y_unit,
        "y_pixel_max_abs": float(np.max(np.abs(y_pixel_clean))),
        "y_max_abs": float(np.max(np.abs(y))),
        "U_max_abs": float(np.max(np.abs(U_seq))),
        "observed_idx_min_compat": int(observed_idx.min()),
        "observed_idx_max_compat": int(observed_idx.max()),
        "save_dense_W": bool(save_dense_W),
    }

    with open(os.path.join(output_dir, "meta.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, indent=2)

    split_info = {
        "split": split,
        "sample_id": int(sample_id),
        "seed": int(seed),
        "observation_mode": observation_mode,
        "obs_face_id": obs_face_id.tolist(),
        "obs_face_vertices": obs_face_vertices.tolist(),
        "obs_barycentric": obs_barycentric.tolist(),
        "observed_idx_compat": observed_idx.tolist(),
        "camera_eye": camera_eye.tolist(),
        "camera_target": camera_target.tolist(),
        "amplitude": float(amplitude),
        "phase": float(phase),
        "frequency_scale": float(frequency_scale),
        "noise_std": float(noise_std),
    }
    with open(os.path.join(output_dir, "split_info.json"), "w", encoding="utf-8") as f:
        json.dump(split_info, f, indent=2)

    return meta


