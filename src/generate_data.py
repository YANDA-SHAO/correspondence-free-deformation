def sample_camera_eye(rng, X0, length_axis=0, radius_range=(1.8, 3.0), elev_range=(0.2, 0.9)):
    center = X0.mean(axis=0).astype(np.float32)
    x_min = float(X0[:, length_axis].min())
    x_max = float(X0[:, length_axis].max())

    target = center.copy()
    target[length_axis] = rng.uniform(
        x_min + 0.35 * (x_max - x_min),
        x_min + 0.85 * (x_max - x_min),
    )

    radius = rng.uniform(radius_range[0], radius_range[1])
    azimuth = rng.uniform(0.0, 2.0 * np.pi)
    elev = rng.uniform(elev_range[0], elev_range[1])

    eye = target.copy()
    eye[0] += radius * np.cos(azimuth)
    eye[1] += radius * np.sin(azimuth)
    eye[2] += elev

    return eye.astype(np.float32), target.astype(np.float32)


def sample_barycentric_points(rng, n):
    """Uniformly sample barycentric coordinates inside triangles."""
    r1 = rng.random(n).astype(np.float32)
    r2 = rng.random(n).astype(np.float32)

    sqrt_r1 = np.sqrt(r1)
    w1 = 1.0 - sqrt_r1
    w2 = sqrt_r1 * (1.0 - r2)
    w3 = sqrt_r1 * r2

    return np.stack([w1, w2, w3], axis=1).astype(np.float32)


def triangle_areas(X0, faces):
    v0 = X0[faces[:, 0]]
    v1 = X0[faces[:, 1]]
    v2 = X0[faces[:, 2]]
    area = 0.5 * np.linalg.norm(np.cross(v1 - v0, v2 - v0), axis=1)
    return area.astype(np.float64)


def select_candidate_faces(X0, faces, length_axis=0, free_end_ratio=0.10):
    """Select faces whose centroid is in the free-end region."""
    centroids = X0[faces].mean(axis=1)
    x = centroids[:, length_axis]
    x_min = float(X0[:, length_axis].min())
    x_max = float(X0[:, length_axis].max())
    threshold = x_max - free_end_ratio * (x_max - x_min)

    candidate_face_id = np.where(x >= threshold)[0].astype(np.int64)
    if len(candidate_face_id) == 0:
        raise ValueError(f"No candidate faces found in the last {free_end_ratio * 100:.1f}% of the beam.")
    return candidate_face_id


def sample_observed_surface_points(X0, faces, rng, K_obs, length_axis=0, free_end_ratio=0.10, area_weighted=True):
    """
    Sample K observation locations on the mesh surface.

    Returns:
        obs_face_id       [K]
        obs_face_vertices [K,3]
        obs_barycentric   [K,3]
        X_obs0            [K,3]
        observed_idx      [K] compatibility: vertex with largest barycentric weight
        candidate_face_id [F_candidate]
    """
    candidate_face_id = select_candidate_faces(X0, faces, length_axis, free_end_ratio)

    if area_weighted:
        areas = triangle_areas(X0, faces)
        prob = areas[candidate_face_id]
        prob = prob / (prob.sum() + 1e-12)
        obs_face_id = rng.choice(candidate_face_id, size=K_obs, replace=True, p=prob)
    else:
        obs_face_id = rng.choice(candidate_face_id, size=K_obs, replace=True)

    obs_face_id = obs_face_id.astype(np.int64)
    obs_face_vertices = faces[obs_face_id].astype(np.int64)
    obs_barycentric = sample_barycentric_points(rng, K_obs)

    X_tri = X0[obs_face_vertices]  # [K,3,3]
    X_obs0 = np.sum(obs_barycentric[:, :, None] * X_tri, axis=1).astype(np.float32)

    dominant_corner = np.argmax(obs_barycentric, axis=1)
    observed_idx = obs_face_vertices[np.arange(K_obs), dominant_corner].astype(np.int64)

    return obs_face_id, obs_face_vertices, obs_barycentric, X_obs0, observed_idx, candidate_face_id.astype(np.int64)


def interpolate_surface_displacement(U_seq, obs_face_vertices, obs_barycentric):
    """
    U_seq: [T,N,3]
    obs_face_vertices: [K,3]
    obs_barycentric: [K,3]

    Returns:
        U_obs_seq: [T,K,3]
    """
    U_tri = U_seq[:, obs_face_vertices, :]  # [T,K,3,3]
    U_obs_seq = np.sum(obs_barycentric[None, :, :, None] * U_tri, axis=2)
    return U_obs_seq.astype(np.float32)


def make_dense_W_gt(N, obs_face_vertices, obs_barycentric):
    K_obs = obs_face_vertices.shape[0]
    W = np.zeros((K_obs, N), dtype=np.float32)
    for k in range(K_obs):
        for j in range(3):
            W[k, obs_face_vertices[k, j]] += obs_barycentric[k, j]
    return W


def make_sparse_W_gt(obs_face_vertices, obs_barycentric):
    return obs_face_vertices.astype(np.int64), obs_barycentric.astype(np.float32)


