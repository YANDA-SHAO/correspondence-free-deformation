def generate_dataset(args):
    mesh_path = Path(args.mesh_path)
    output_dir = Path(args.output_dir)

    if not mesh_path.exists():
        raise FileNotFoundError(f"Cannot find mesh file: {mesh_path.resolve()}\nPlease check --mesh_path.")

    print("=" * 80)
    print("Generating dataset")
    print("mesh_path:", mesh_path.resolve())
    print("output_dir:", output_dir.resolve())
    print("observation_mode:", args.observation_mode)
    print("=" * 80)

    mesh = trimesh.load_mesh(str(mesh_path), process=False)
    if mesh.vertices is None or len(mesh.vertices) == 0:
        raise ValueError(f"Loaded mesh has no vertices: {mesh_path}")
    if mesh.faces is None or len(mesh.faces) == 0:
        raise ValueError(f"Loaded mesh has no faces: {mesh_path}")

    dataset_rng = np.random.default_rng(args.seed)

    split_specs = [("train", args.num_train), ("val", args.num_val), ("test", args.num_test)]

    dataset_meta = {
        "mesh_path": str(mesh_path),
        "output_dir": str(output_dir),
        "seed": int(args.seed),
        "fair_split_rule": (
            "Same beam geometry. Train/val/test are split by sample, not by frame. "
            "Each sample has its own surface observation points, camera, amplitude, phase, frequency_scale, and noise."
        ),
        "observation_mode": args.observation_mode,
        "correspondence_type": "surface barycentric soft correspondence" if args.observation_mode == "surface" else "vertex one-hot correspondence",
        "num_train": int(args.num_train),
        "num_val": int(args.num_val),
        "num_test": int(args.num_test),
        "T": int(args.T),
        "K_obs": int(args.K_obs),
        "free_end_ratio": float(args.free_end_ratio),
        "amplitude_range": [float(args.amp_min), float(args.amp_max)],
        "frequency_scale_range": [float(args.freq_scale_min), float(args.freq_scale_max)],
        "noise_std_range": [float(args.noise_std_min), float(args.noise_std_max)],
        "normalize_y": bool(not args.no_normalize_y),
        "save_dense_W": bool(args.save_dense_W),
        "notes": (
            "For real-video-style testing, model input can be 2D tracking trajectories y. "
            "The barycentric files provide synthetic ground-truth soft correspondence for W supervision."
        ),
    }

    output_dir.mkdir(parents=True, exist_ok=True)
    with open(output_dir / "dataset_meta.json", "w", encoding="utf-8") as f:
        json.dump(dataset_meta, f, indent=2)

    all_summaries = []

    for split, count in split_specs:
        split_dir = output_dir / split
        split_dir.mkdir(parents=True, exist_ok=True)
        print(f"\n[{split}] generating {count} samples")

        for i in range(count):
            sample_seed = int(dataset_rng.integers(0, 2**31 - 1))
            rng = np.random.default_rng(sample_seed)

            amplitude = float(rng.uniform(args.amp_min, args.amp_max))
            phase = float(rng.uniform(0.0, 2.0 * np.pi))
            frequency_scale = float(rng.uniform(args.freq_scale_min, args.freq_scale_max))
            noise_std = float(rng.uniform(args.noise_std_min, args.noise_std_max))

            sample_dir = split_dir / f"sample_{i:04d}"

            meta = generate_sample(
                mesh=mesh,
                mesh_path=mesh_path,
                output_dir=sample_dir,
                seed=sample_seed,
                split=split,
                sample_id=i,
                youngs_modulus=args.youngs_modulus,
                density=args.density,
                width=args.width,
                height=args.height,
                length=args.length,
                amplitude=amplitude,
                T=args.T,
                duration=args.duration,
                K_obs=args.K_obs,
                noise_std=noise_std,
                length_axis=args.length_axis,
                displacement_axis=args.displacement_axis,
                fx=args.fx,
                fy=args.fy,
                cx=args.cx,
                cy=args.cy,
                camera_eye=None,
                camera_target=None,
                normalize_y=not args.no_normalize_y,
                free_end_ratio=args.free_end_ratio,
                phase=phase,
                frequency_scale=frequency_scale,
                observation_mode=args.observation_mode,
                area_weighted_surface=not args.no_area_weighted_surface,
                save_dense_W=args.save_dense_W,
            )

            all_summaries.append({
                "split": split,
                "sample": f"sample_{i:04d}",
                "seed": sample_seed,
                "observation_mode": meta["observation_mode"],
                "correspondence_type": meta["correspondence_type"],
                "amplitude": meta["amplitude"],
                "frequency_hz": meta["frequency_hz"],
                "phase": meta["phase"],
                "noise_std": meta["noise_std"],
                "y_pixel_max_abs": meta["y_pixel_max_abs"],
                "y_max_abs": meta["y_max_abs"],
                "U_max_abs": meta["U_max_abs"],
            })

            if (i + 1) % max(1, args.print_every) == 0 or (i + 1) == count:
                print(
                    f"  {split} {i + 1:04d}/{count:04d} | "
                    f"A={amplitude:.5f}, freq_scale={frequency_scale:.3f}, "
                    f"noise={noise_std:.2e}, y_pix_max={meta['y_pixel_max_abs']:.3f}, "
                    f"U_max={meta['U_max_abs']:.4f}"
                )

    with open(output_dir / "samples_summary.json", "w", encoding="utf-8") as f:
        json.dump(all_summaries, f, indent=2)

    print("\nDone.")
    print("Dataset saved to:", output_dir.resolve())
    print("Next:")
    print(f"  python src\\check_data.py --data_dir {output_dir}\\train\\sample_0000")


